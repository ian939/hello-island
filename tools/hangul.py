# 동물 울음소리처럼 영어로 적힌 소리는 한국 아이에게 익숙한 소리로
READ.update({'woof': '우프', 'meow': '미아우'})


def key(token):
    import re
    return re.sub(r"[^A-Za-z'-]", '', token).lower()


def read_sentence(sentence):
    """낱말마다 한글 읽기 (문장의 공백 기준 낱말과 순서가 같다)."""
    out = []
    for tok in sentence.split():
        k = key(tok)
        if k not in READ:
            raise KeyError(k)
        out.append(READ[k])
    return out
